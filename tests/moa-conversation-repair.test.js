const fs=require('fs'),vm=require('vm');
const ok=(v,m)=>{if(!v)throw new Error(m)};
const engine=fs.readFileSync('js/ai/moa-communication-engine.js','utf8');
const store={};const fakeMath=Object.create(Math);fakeMath.random=()=>0;
const sandbox={console,Date,Math:fakeMath,setTimeout:()=>1,clearTimeout:()=>{},MiniTalk:{AI:{},Store:{get:()=>({user_id:'u-repair',isGuest:false})},Persistence:{get:(k,d)=>k in store?store[k]:d,set:(k,v)=>store[k]=v,remove:k=>delete store[k]},AuthApi:{moaSync:async()=>({}),moaSearch:async()=>({}),moaCommit:async()=>({})}}};
vm.createContext(sandbox);vm.runInContext(engine,sandbox);
(async()=>{const e=sandbox.MiniTalk.AI.MoaCommunicationEngine;
  let r=await e.reply('오늘 점심 뭐먹지');
  ok(/점심|제육|돈까스|김밥|국수|볶음밥|덮밥/.test(r.reply),'meal question was not answered concretely: '+r.reply);
  ok(!/그렇구나|듣고 있어|듣고있어/.test(r.reply),'meal question fell into generic acknowledgement: '+r.reply);
  r=await e.reply('뭐가 그렇구나야 점심 뭐먹을까 물었는데');
  ok(/방금 답이 엉뚱|점심|제육|돈까스|김밥|국수|덮밥/.test(r.reply),'repair did not recover embedded meal question: '+r.reply);
  r=await e.reply('한심하긴');
  ok(!/갑자기 왜|헛소리했어\?/.test(r.reply),'criticism was treated as jokey insult banter: '+r.reply);
  e.clearContext();
  r=await e.reply('오늘 뭐하지');
  ok(/산책|게임|영상|간식|걷/.test(r.reply),'activity decision not answered: '+r.reply);
  console.log('MOA_CONVERSATION_REPAIR_OK');
})().catch(e=>{console.error(e);process.exit(1)});
